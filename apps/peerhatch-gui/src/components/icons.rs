use gpui::{prelude::*, *};
use peerhatch_control::DevicePlatform;

#[derive(Clone, Copy)]
pub enum Icon {
    Home,
    Monitor,
    Windows,
    Penguin,
    Finder,
    Globe,
    Sun,
    Moon,
    Check,
    Copy,
    Refresh,
    Filter,
    FilterX,
    Settings,
    Menu,
    ChevronDown,
    ChevronUp,
    ChevronRight,
    TabsOnLeft,
    CollapseSidebar,
    ExpandSidebar,
    TabsOnTop,
    Terminal,
    Plus,
}

impl Icon {
    pub fn device(platform: DevicePlatform) -> Self {
        match platform {
            DevicePlatform::Windows => Self::Windows,
            DevicePlatform::Linux => Self::Penguin,
            DevicePlatform::MacOs => Self::Finder,
            DevicePlatform::Web => Self::Globe,
            DevicePlatform::Unknown => Self::Monitor,
        }
    }

    /// Draw a monochrome icon on a 16-point grid using the element's text color.
    pub fn draw(self, size: f32) -> impl IntoElement {
        const FRAME: &[(f32, f32)] = &[
            (1.5, 2.5),
            (14.5, 2.5),
            (14.5, 13.5),
            (1.5, 13.5),
            (1.5, 2.5),
        ];
        const FILTER: &[(f32, f32)] = &[
            (1.5, 2.),
            (14.5, 2.),
            (9., 8.5),
            (9., 12.),
            (6.5, 13.5),
            (6.5, 8.5),
            (1.5, 2.),
        ];
        let strokes: &[&[(f32, f32)]] = match self {
            Self::Home => &[
                &[(1., 7.4), (8., 1.8), (15., 7.4)],
                &[
                    (3., 6.),
                    (3., 14.),
                    (6.5, 14.),
                    (6.5, 9.),
                    (9.5, 9.),
                    (9.5, 14.),
                    (13., 14.),
                    (13., 6.),
                ],
            ],
            Self::Monitor => &[
                &[(1.5, 2.5), (14.5, 2.5), (14.5, 11.), (1.5, 11.), (1.5, 2.5)],
                &[(8., 11.), (8., 14.)],
                &[(5., 14.), (11., 14.)],
            ],
            Self::Windows => &[
                &[(1.5, 1.5), (7.3, 1.5), (7.3, 7.3), (1.5, 7.3), (1.5, 1.5)],
                &[(8.7, 1.5), (14.5, 1.5), (14.5, 7.3), (8.7, 7.3), (8.7, 1.5)],
                &[(1.5, 8.7), (7.3, 8.7), (7.3, 14.5), (1.5, 14.5), (1.5, 8.7)],
                &[
                    (8.7, 8.7),
                    (14.5, 8.7),
                    (14.5, 14.5),
                    (8.7, 14.5),
                    (8.7, 8.7),
                ],
            ],
            Self::Penguin => &[
                &[
                    (4.1, 12.),
                    (3.1, 10.6),
                    (3.7, 8.7),
                    (5.2, 6.2),
                    (5.4, 3.3),
                    (6.4, 1.9),
                    (8., 1.4),
                    (9.6, 1.9),
                    (10.6, 3.3),
                    (10.8, 6.2),
                    (12.3, 8.7),
                    (12.9, 10.6),
                    (11.9, 12.),
                ],
                &[(6.4, 4.1), (6.6, 4.8)],
                &[(9.6, 4.1), (9.4, 4.8)],
                &[(6.3, 6.), (8., 5.4), (9.7, 6.), (8., 7.1), (6.3, 6.)],
                &[
                    (5.1, 11.2),
                    (2.6, 13.6),
                    (3.1, 14.5),
                    (6.3, 14.2),
                    (6.7, 13.1),
                    (9.3, 13.1),
                    (9.7, 14.2),
                    (12.9, 14.5),
                    (13.4, 13.6),
                    (10.9, 11.2),
                ],
            ],
            Self::Finder => &[
                FRAME,
                &[(8.6, 2.5), (7.1, 8.6), (9., 8.6), (9.3, 13.5)],
                &[(4.7, 5.2), (4.7, 6.8)],
                &[(11.5, 5.2), (11.5, 6.8)],
                &[(4., 9.4), (6., 10.7), (8., 11.), (10., 10.7), (12., 9.4)],
            ],
            Self::Globe => &[
                &[
                    (8., 1.5),
                    (11.3, 2.4),
                    (13.6, 4.7),
                    (14.5, 8.),
                    (13.6, 11.3),
                    (11.3, 13.6),
                    (8., 14.5),
                    (4.7, 13.6),
                    (2.4, 11.3),
                    (1.5, 8.),
                    (2.4, 4.7),
                    (4.7, 2.4),
                    (8., 1.5),
                ],
                &[
                    (8., 1.5),
                    (6.2, 4.4),
                    (5.5, 8.),
                    (6.2, 11.6),
                    (8., 14.5),
                    (9.8, 11.6),
                    (10.5, 8.),
                    (9.8, 4.4),
                    (8., 1.5),
                ],
                &[(1.5, 8.), (14.5, 8.)],
            ],
            Self::Sun => &[
                &[
                    (8., 4.6),
                    (10.4, 5.6),
                    (11.4, 8.),
                    (10.4, 10.4),
                    (8., 11.4),
                    (5.6, 10.4),
                    (4.6, 8.),
                    (5.6, 5.6),
                    (8., 4.6),
                ],
                &[(8., 1.), (8., 3.)],
                &[(8., 13.), (8., 15.)],
                &[(1., 8.), (3., 8.)],
                &[(13., 8.), (15., 8.)],
                &[(3., 3.), (4.4, 4.4)],
                &[(11.6, 11.6), (13., 13.)],
                &[(3., 13.), (4.4, 11.6)],
                &[(11.6, 4.4), (13., 3.)],
            ],
            Self::Moon => &[&[
                (12.8, 10.7),
                (10.4, 11.),
                (7.9, 10.2),
                (6., 8.4),
                (5.1, 5.9),
                (5.3, 3.2),
                (3.3, 5.),
                (2.5, 7.8),
                (3., 10.4),
                (4.6, 12.4),
                (7.2, 13.5),
                (9.7, 13.3),
                (11.6, 12.3),
                (12.8, 10.7),
            ]],
            Self::Copy => &[
                &[(6., 6.), (14., 6.), (14., 14.), (6., 14.), (6., 6.)],
                &[(9.8, 4.), (9.8, 2.), (2., 2.), (2., 9.8), (4., 9.8)],
            ],
            Self::Refresh => &[
                &[
                    (13.4, 6.5),
                    (12.8, 4.7),
                    (11.4, 3.2),
                    (9.6, 2.4),
                    (7.6, 2.2),
                    (5.6, 2.7),
                    (4., 3.9),
                    (2.9, 5.6),
                    (2.5, 7.6),
                    (2.8, 9.6),
                    (3.8, 11.4),
                    (5.4, 12.7),
                    (7.4, 13.4),
                    (9.4, 13.3),
                    (11.3, 12.4),
                    (12.6, 11.),
                ],
                &[(13.5, 2.4), (13.5, 6.6), (9.3, 6.6)],
            ],
            Self::Check => &[&[(2.5, 8.), (6., 11.5), (13.5, 4.)]],
            Self::Filter => &[FILTER],
            Self::FilterX => &[
                FILTER,
                &[(10.8, 10.5), (14.8, 14.5)],
                &[(14.8, 10.5), (10.8, 14.5)],
            ],
            Self::Settings => &[
                &[(1., 5.), (4., 5.)],
                &[(7.5, 5.), (15., 5.)],
                &[(4., 3.), (7.5, 3.), (7.5, 7.), (4., 7.), (4., 3.)],
                &[(1., 11.), (9., 11.)],
                &[(12.5, 11.), (15., 11.)],
                &[(9., 9.), (12.5, 9.), (12.5, 13.), (9., 13.), (9., 9.)],
            ],
            Self::Menu => &[
                &[(2., 3.5), (14., 3.5)],
                &[(2., 8.), (14., 8.)],
                &[(2., 12.5), (14., 12.5)],
            ],
            Self::ChevronDown => &[&[(3.5, 6.), (8., 10.5), (12.5, 6.)]],
            Self::ChevronUp => &[&[(3.5, 10.), (8., 5.5), (12.5, 10.)]],
            Self::ChevronRight => &[&[(6., 3.5), (10.5, 8.), (6., 12.5)]],
            Self::TabsOnLeft => &[FRAME, &[(5.5, 2.5), (5.5, 13.5)]],
            Self::CollapseSidebar => &[
                FRAME,
                &[(5.5, 2.5), (5.5, 13.5)],
                &[(11.5, 5.5), (9., 8.), (11.5, 10.5)],
            ],
            Self::ExpandSidebar => &[
                FRAME,
                &[(5.5, 2.5), (5.5, 13.5)],
                &[(9., 5.5), (11.5, 8.), (9., 10.5)],
            ],
            Self::TabsOnTop => &[FRAME, &[(1.5, 6.), (14.5, 6.)]],
            Self::Terminal => &[
                &[(2., 3.5), (6.5, 8.), (2., 12.5)],
                &[(8., 12.5), (14., 12.5)],
            ],
            Self::Plus => &[&[(8., 2.5), (8., 13.5)], &[(2.5, 8.), (13.5, 8.)]],
        };
        canvas(
            |_, _, _| (),
            move |bounds, _, window, _| {
                let scale = size / 16.;
                let mut path = match self {
                    Self::Windows => PathBuilder::fill(),
                    _ => PathBuilder::stroke(px(1.4 * scale)),
                };
                for stroke in strokes {
                    if let Some((&(x, y), rest)) = stroke.split_first() {
                        path.move_to(point(px(x), px(y)));
                        for &(x, y) in rest {
                            path.line_to(point(px(x), px(y)));
                        }
                    }
                }
                path.scale(scale);
                path.translate(bounds.origin);
                if let Ok(path) = path.build() {
                    window.paint_path(path, window.text_style().color);
                }
            },
        )
        .size(px(size))
        .flex_none()
    }

    pub fn label(self, text: impl Into<SharedString>) -> Div {
        div()
            .flex()
            .min_w_0()
            .items_center()
            .gap_2()
            .child(self.draw(16.))
            .child(div().min_w_0().truncate().child(text.into()))
    }
}
